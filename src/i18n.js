export function normalizeLocale(value) {
  const normalized = String(value || "").trim().toLowerCase();
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
  return "ja";
}

export function translate(locale, key, variables = {}) {
  const active = MESSAGES[normalizeLocale(locale)] || MESSAGES.ja;
  const template = active[key] ?? MESSAGES.ja[key] ?? key;
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => String(variables[name] ?? ""));
}

export function localeNumberFormat(locale) {
  return new Intl.NumberFormat(normalizeLocale(locale));
}

export function isNativeLocale(value) {
  const normalized = String(value || "").trim().toLowerCase().replaceAll("_", "-");
  return normalized === "ja" || normalized.startsWith("ja-")
    || normalized === "en" || normalized.startsWith("en-")
    || normalized === "zh" || normalized.startsWith("zh-");
}

export function missingTranslationKeys(locale) {
  const active = MESSAGES[normalizeLocale(locale)] || {};
  return Object.keys(MESSAGES.ja).filter((key) => !Object.hasOwn(active, key));
}
